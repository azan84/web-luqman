// Builds src/knowledge.js: a compact map of the site's study materials so the
// study bot can point students to the right notes, flash cards and games.
// The bot teaches from its own knowledge; this is only the "where to find it" list.
// Re-run (npm run deploy does it) after adding or renaming study pages.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, "../..");
const outFile = path.resolve(here, "../src/knowledge.js");
const SITE = "https://luqman.biomechemical.com";

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", ndash: "–", mdash: "—", middot: "·", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", hellip: "…", times: "×", divide: "÷", rarr: "→", larr: "←", bull: "•", copy: "©", deg: "°", sup2: "²", sup3: "³" };

function decode(s) {
  return s.replace(/&(#x[0-9a-f]+|#\d+|[a-z0-9]+);/gi, (m, e) => {
    if (e[0] === "#") {
      const n = e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(n) ? String.fromCodePoint(n) : m;
    }
    return ENTITIES[e] ?? ENTITIES[e.toLowerCase()] ?? m;
  });
}

function htmlToText(html) {
  let s = html;
  s = s.replace(/<head[\s\S]*?<\/head>/i, "");
  s = s.replace(/<(script|style|noscript|nav|header|footer|svg|canvas|template)\b[\s\S]*?<\/\1>/gi, " ");
  s = s.replace(/<!--[\s\S]*?-->/g, " ");
  // Keep link targets so the bot can send students to the right page.
  s = s.replace(/<a\b[^>]*href\s*=\s*"([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi, (m, href, inner) => {
    const text = inner.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
    if (!text) return " ";
    if (href === "#" || href === "") return ` ${text} (link not available yet) `;
    if (/^(#|javascript:)/i.test(href)) return ` ${text} `;
    return ` ${text} [${href}] `;
  });
  s = s.replace(/<(h[1-6])\b[^>]*>/gi, (m, h) => `\n\n${"#".repeat(Math.min(+h[1] + 1, 6))} `);
  s = s.replace(/<li\b[^>]*>/gi, "\n- ");
  s = s.replace(/<(br|hr)\b[^>]*>/gi, "\n");
  s = s.replace(/<\/?(p|div|section|article|ul|ol|table|tr|blockquote|figure|figcaption|h[1-6]|dl|dt|dd|main|aside|button)\b[^>]*>/gi, "\n");
  s = s.replace(/<[^>]+>/g, " ");
  s = decode(s);
  return s
    .split("\n")
    .map((l) => l.replace(/[ \t ]+/g, " ").trim())
    .filter((l, i, a) => l && l !== "-" && l !== a[i - 1])
    .join("\n")
    .replace(/\n(#+ )/g, "\n\n$1")
    .trim();
}

function title(html, file) {
  return decode((html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? file).trim());
}

// Main pages, in full (they are short).
const PAGES = ["index.html", "studies.html", "games.html"];
const sections = PAGES.filter((f) => fs.existsSync(path.join(siteRoot, f))).map((file) => {
  const html = fs.readFileSync(path.join(siteRoot, file), "utf8");
  const url = file === "index.html" ? `${SITE}/` : `${SITE}/${file}`;
  return `=== PAGE: ${title(html, file)}\nURL: ${url} (relative link: ${file})\n\n${htmlToText(html)}`;
});

// Each study page: its title and chapter headings, not the full notes.
const studyDir = path.join(siteRoot, "studies");
const studyPages = fs.existsSync(studyDir)
  ? fs.readdirSync(studyDir).sort().flatMap((dir) =>
      fs.readdirSync(path.join(studyDir, dir)).filter((f) => f.endsWith(".html")).sort().map((f) => `studies/${dir}/${f}`))
  : [];
const index = studyPages.map((file) => {
  const html = fs.readFileSync(path.join(siteRoot, file), "utf8");
  const body = html.replace(/<(script|style|svg|template)\b[\s\S]*?<\/\1>/gi, " ");
  const heads = [...body.matchAll(/<h2\b[^>]*>([\s\S]*?)<\/h2>/gi)]
    .map((m) => decode(m[1].replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim())
    .filter(Boolean);
  const unique = [...new Set(heads)].slice(0, 20);
  return `- ${title(html, file)} — relative link: ${file}${unique.length ? `\n  Sections: ${unique.join(" · ")}` : ""}`;
});
sections.push(`=== STUDY PAGES (title, link and section headings)\n\n${index.join("\n")}`);

const knowledge = sections.join("\n\n");
fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-knowledge.mjs — do not edit by hand.\nexport default ${JSON.stringify(knowledge)};\n`,
);
console.log(`knowledge.js: ${PAGES.length} pages + ${studyPages.length} study pages, ${knowledge.length.toLocaleString()} chars (~${Math.round(knowledge.length / 4).toLocaleString()} tokens)`);
